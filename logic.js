// ===== ФУНКЦИЯ РАСЧЁТА РЕЗУЛЬТАТА =====
function calculateResult(answers) {
    const scores = { A: 0, B: 0, C: 0, D: 0, E: 0 };
    
    answers.forEach(profile => {
        if (profile && scores[profile] !== undefined) {
            scores[profile]++;
        }
    });
    
    // Сортируем по убыванию
    const sorted = Object.entries(scores).sort((a, b) => b[1] - a[1]);
    const first = sorted[0];
    const second = sorted[1];
    
    // Проверяем разницу: если <= 1 и второй не нулевой — предлагаем оба
    const diff = first[1] - second[1];
    const recommendedAxes = [first[0]];
    
    if (diff <= 1 && second[1] > 0) {
        recommendedAxes.push(second[0]);
    }
    
    // Получаем программы по осям
    const result = {
        axes: recommendedAxes,
        scores: scores,
        programs: recommendedAxes.map(axis => programMap[axis] || [])
    };
    
    return result;
}

