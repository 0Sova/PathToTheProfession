function getProgramDetails(title) {
    // Проходим по всем осям в programMap
    for (const axisKey in programMap) {
        const programs = programMap[axisKey];
        // Ищем программу с нужным названием
        const found = programs.find(p => p.title === title);
        if (found) {
            // Возвращаем найденную программу (с roadmap и missions)
            return found;
        }
    }
    return null; // Если программа не найдена
}